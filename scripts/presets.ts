/**
 * Writes src/core/presets.gen.ts from presets/: every file of presets/<locale>/ as a string
 * constant keyed by its path there. Rerun under Node 24 after changing presets/:
 *
 *   npm run presets
 *
 * It copies and interprets nothing: `gitignore` keeps its name and dotoriwiki.yaml keeps the
 * preset's time_zone (src/core/presets.ts applies both), so the test that holds the module to
 * presets/ needs neither rule. Paths are NFC, because a Mac checkout can hand back NFD names.
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const ROOT = join(import.meta.dirname, '..');
const LOCALES = ['en', 'ko'] as const;

function files(dir: string): [string, string][] {
  return readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((e) => e.isFile())
    .map((e): [string, string] => {
      const full = join(e.parentPath, e.name);
      return [relative(dir, full).split(sep).join('/').normalize('NFC'), readFileSync(full, 'utf8')];
    })
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
}

const body = LOCALES.map((l) => {
  const entries = files(join(ROOT, 'presets', l)).map(([path, text]) => `    ${JSON.stringify(path)}: ${JSON.stringify(text)},`);
  return `  ${l}: {\n${entries.join('\n')}\n  },`;
}).join('\n');

writeFileSync(
  join(ROOT, 'src', 'core', 'presets.gen.ts'),
  `// Generated by scripts/presets.ts from presets/. Do not edit: change presets/, then run npm run presets.\n\nexport const PRESET_SOURCE = {\n${body}\n} as const satisfies { readonly [locale: string]: { readonly [path: string]: string } };\n`,
);
